export const foodCategories = [...new Set(foodLibrary.map((food) => food.category))];

export function searchFoods(
  query: string,
  category = '全部',
  favorites: string[] = [],
): LibraryFood[] {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return foodLibrary.filter((food) => {
    if (
      category === '常用'
        ? !favorites.includes(food.id)
        : category !== '全部' && food.category !== category
    )
      return false;
    const text = [food.name, ...food.aliases].join(' ').toLocaleLowerCase();
    return words.every((word) => text.includes(word));
  });
}

export function foodCalories(food: Pick<LibraryFood, 'kcalPer100g'>, grams: number): number {
  if (!Number.isFinite(grams) || grams <= 0 || grams > 10000)
    throw new Error('份量需大于 0 且不超过 10000 克');
  return Math.round((food.kcalPer100g * grams) / 100);
}
